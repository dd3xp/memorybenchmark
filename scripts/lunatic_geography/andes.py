def terrain(geo,name):
    d=Drawing(name,5200,6300,'#d5d8c2')
    d.polygon([(0,0),(900,0),(1300,900),(860,2000),(1050,3000),(780,4500),(1500,6300),(0,6300)],'#cbb895',opacity=.8)
    d.forest([(4400,200),(5200,0),(5200,6300),(4140,6300),(4630,4700),(4320,3300),(4870,1900)],743,colour='#a7bc9b',trees=190)
    for x,y,rx,ry in [(1300,2600,490,900),(1700,3700,390,690),(3570,1620,490,770),(3050,3920,470,710)]:
        for f in (1,.8,.6):d.path(organic(x,y,rx*f,ry*f,.2),fill='#b2b39c',stroke='#929d8b',width=3,opacity=.45)
    for p in geo['features']['rocks']:d.polygon(p,'#8e9383','#7c887a',3,.8)
    for p in geo['features']['lakes']:d.polygon(p,'#87acaf','#b9c7b9',10)
    for x,y in [(1850,1400),(2400,3200),(2050,4100),(4400,4850),(1000,5400)]:
        d.settlement(x+50,y-80,170,130,25,x+y,buildings=16)
    return d.finish()
